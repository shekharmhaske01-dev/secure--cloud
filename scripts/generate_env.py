#!/usr/bin/env python3
"""Interactive .env generator for SecureCloud.

Usage:
    python scripts/generate_env.py

Generates cryptographic secrets and walks through storage backend
configuration, then writes a production-ready .env file.
"""
from __future__ import annotations

import base64
import os
import secrets
import sys


def prompt(msg: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    val = input(f"  {msg}{suffix}: ").strip()
    return val or default


def main() -> None:
    print("\n╔══════════════════════════════════════════════╗")
    print("║   SecureCloud — Environment Configuration   ║")
    print("╚══════════════════════════════════════════════╝\n")

    env: dict[str, str] = {}

    # ── Secrets ───────────────────────────────────────────────────────────
    print("► Generating cryptographic secrets ...\n")
    env["SECRET_KEY"] = secrets.token_urlsafe(48)
    env["SECURECLOUD_KEY_ENCRYPTION_KEY"] = base64.b64encode(os.urandom(32)).decode()

    print(f"  SECRET_KEY                       = {env['SECRET_KEY']}")
    print(f"  SECURECLOUD_KEY_ENCRYPTION_KEY   = {env['SECURECLOUD_KEY_ENCRYPTION_KEY']}")
    print()
    print("  ⚠  SAVE the Key-Encryption Key (KEK) — losing it means ALL files")
    print("     become permanently unrecoverable.\n")

    # ── Environment ──────────────────────────────────────────────────────
    env["FLASK_ENV"] = prompt("Environment (development/production)", "production")

    # ── Storage backend ──────────────────────────────────────────────────
    print("\n► Storage backend\n")
    print("  1. local  — filesystem (default, good for single-server)")
    print("  2. s3     — S3-compatible (Neon, MinIO, AWS S3)")
    print("  3. hdfs   — Hadoop Distributed File System\n")

    choice = prompt("Choose storage backend (1/2/3)", "1")
    backend_map = {"1": "local", "2": "s3", "3": "hdfs"}
    backend = backend_map.get(choice, "local")
    env["SECURECLOUD_STORAGE_BACKEND"] = backend

    if backend == "s3":
        print("\n  S3-compatible storage settings:\n")
        env["NEON_STORAGE_ENDPOINT_URL"] = prompt("Endpoint URL (e.g. https://s3.us-east-2.amazonaws.com)")
        env["NEON_STORAGE_REGION"] = prompt("Region", "us-east-2")
        env["NEON_STORAGE_BUCKET"] = prompt("Bucket name", "securecloud")
        env["NEON_STORAGE_ACCESS_KEY_ID"] = prompt("Access Key ID")
        env["NEON_STORAGE_SECRET_ACCESS_KEY"] = prompt("Secret Access Key")
    elif backend == "hdfs":
        print("\n  HDFS settings:\n")
        env["HDFS_NAMENODE_URL"] = prompt("NameNode URL", "http://localhost:9870")
        env["HDFS_USER"] = prompt("HDFS user", "root")
        env["HDFS_ROOT_PATH"] = prompt("Root path", "/securecloud")

    # ── Optional settings ────────────────────────────────────────────────
    print("\n► Optional settings (press Enter to accept defaults)\n")
    env["SECURECLOUD_BLOCK_SIZE"] = prompt("Block size in bytes", "1048576")
    env["SECURECLOUD_MAX_UPLOAD_BYTES"] = prompt("Max upload size in bytes", "268435456")
    env["SECURECLOUD_SESSION_COOKIE_SECURE"] = prompt("Secure session cookie (true for HTTPS)", "true")
    env["LOG_LEVEL"] = prompt("Log level", "INFO")

    # ── Write .env ───────────────────────────────────────────────────────
    env_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), ".env")

    if os.path.exists(env_path):
        overwrite = prompt(f"\n  .env already exists. Overwrite? (y/n)", "n")
        if overwrite.lower() != "y":
            print("\n  Aborted. Existing .env was NOT modified.\n")
            return

    lines = [f"# SecureCloud .env — generated by generate_env.py\n"]
    for key, val in env.items():
        lines.append(f"{key}={val}\n")

    with open(env_path, "w") as f:
        f.writelines(lines)

    print(f"\n  ✓ .env written to: {env_path}")
    print("\n  Next steps:")
    print("    1. Review .env and adjust as needed")
    print("    2. Run:  python scripts/init_db.py")
    print("    3. Run:  gunicorn app:app --config gunicorn.conf.py")
    print()


if __name__ == "__main__":
    main()
